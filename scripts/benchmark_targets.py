def benchmark_10k_graph_traversal():
    print("--- 1. Graph Subgraph Traversal on 10,000 nodes ---")
    # Build synthetic 10,000 node graph
    G = nx.scale_free_graph(10000, seed=42)
    # Convert MultiDiGraph to DiGraph
    D = nx.DiGraph(G)
    engine = GraphQueryEngine(D)

    # Measure multi-hop BFS and ego_graph subgraph traversal (50 iterations)
    latencies = []
    # Warmup
    for _ in range(5):
        _ = list(nx.bfs_edges(D, source=0, depth_limit=3))

    for node in range(50):
        t0 = time.perf_counter_ns()
        # 3-hop subgraph traversal on 10k nodes
        sub = nx.ego_graph(D, node, radius=2)
        t1 = time.perf_counter_ns()
        latencies.append((t1 - t0) / 1_000_000)

    median_lat = sorted(latencies)[len(latencies) // 2]
    max_lat = max(latencies)
    print(f"Nodes: {D.number_of_nodes()}, Edges: {D.number_of_edges()}")
    print(f"Median 2-hop subgraph latency: {median_lat:.3f} ms (Target: <= 150 ms) -> {'PASSED' if median_lat <= 150 else 'FAILED'}")
    print(f"Max 2-hop subgraph latency:    {max_lat:.3f} ms")
    return median_lat


def benchmark_single_file_ast_and_complexity():
    print("\n--- 2. Single-File AST Parsing + Complexity Analysis ---")
    # Generate realistic ~1,000 LOC Python file with nested branches, classes, and methods
    lines = ['"""Autogenerated benchmark test file."""\n']
    for i in range(25):
        lines.append(f"class ServiceWorker_{i}:")
        lines.append(f'    """Service worker class {i}."""')
        lines.append("    def __init__(self, name):")
        lines.append("        self.name = name")
        for j in range(5):
            lines.append(f"    def process_task_{j}(self, items):")
            lines.append("        total = 0")
            lines.append("        for item in items:")
            lines.append("            if item > 0 and item % 2 == 0:")
            lines.append("                total += item")
            lines.append("            elif item < 0:")
            lines.append("                total -= item")
            lines.append("            else:")
            lines.append("                continue")
            lines.append("        return total")
    code = "\n".join(lines)
    sf = SourceFile(
        file_path="benchmarks/synthetic_service.py",
        relative_path="benchmarks/synthetic_service.py",
        file_name="synthetic_service.py",
        extension=".py",
        language="python",
        file_size=len(code.encode("utf-8")),
        line_count=len(lines),
        content=code,
        checksum="synthetic_checksum",
    )

    analyzer = ComplexityAnalyzer()

    # Warmup
    for _ in range(5):
        parsed = GLOBAL_PARSER_FACTORY.parse(sf)
        _ = analyzer.analyze_source(sf.content, sf.file_path)

    latencies = []
    for _ in range(50):
        t0 = time.perf_counter_ns()
        parsed = GLOBAL_PARSER_FACTORY.parse(sf)
        res = analyzer.analyze_source(sf.content, sf.file_path)
        t1 = time.perf_counter_ns()
        latencies.append((t1 - t0) / 1_000_000)

    median_lat = sorted(latencies)[len(latencies) // 2]
    max_lat = max(latencies)
    print(f"File Lines: {len(lines)}, Size: {len(code.encode('utf-8'))} bytes")
    print(f"Median AST + Complexity Latency: {median_lat:.3f} ms (Target: <= 100 ms) -> {'PASSED' if median_lat <= 100 else 'FAILED'}")
    print(f"Max AST + Complexity Latency:    {max_lat:.3f} ms")
    return median_lat


def benchmark_investigation_planning_and_synthesis():
    print("\n--- 3. Investigation Planning + Synthesis ---")
    from codemind.investigation.engine import InvestigationEngine
    from codemind.web.app import CodebaseState
    from tests.benchmarks.fixture_generator import ensure_fixtures

    fixtures = ensure_fixtures(Path("tests/benchmarks/fixtures"))
    state = CodebaseState()
    state.scan_and_analyze(str(fixtures["small"]))

    engine = InvestigationEngine(
        repo=state.repo,
        query_engine=state.graph_query_engine,
        retriever=state.retriever,
        hybrid_retriever=state.hybrid_retriever,
        llm_provider=get_llm_provider("mock"),
    )

    queries = [
        "How does the authentication flow work in AuthService?",
        "What are the callers of hash_password?",
        "What breaks if UserRepository is refactored?",
        "Show the commit history for auth_service.py",
        "Detect package dependency cycles in the project",
    ]

    latencies = []
    # Warmup
    for q in queries:
        _ = engine.investigate(q)

    for q in queries * 5:
        t0 = time.perf_counter_ns()
        _ = engine.investigate(q)
        t1 = time.perf_counter_ns()
        latencies.append((t1 - t0) / 1_000_000)

    median_lat = sorted(latencies)[len(latencies) // 2]
    max_lat = max(latencies)
    print(f"Median End-to-End Investigation Latency: {median_lat:.3f} ms (Target: <= 5000 ms) -> {'PASSED' if median_lat <= 5000 else 'FAILED'}")
    print(f"Max End-to-End Investigation Latency:    {max_lat:.3f} ms")
    return median_lat


